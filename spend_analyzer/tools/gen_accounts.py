"""Generate accounts.yaml from the account_ids seen in the archive.

Name, type, subtype and institution are seeded from the collector's CSV, the one
local file that carries Plaid's account identity (the stores hold only the id).
Without the CSV they fall back to placeholders for the human to fill in. It
never overwrites an existing file unless forced (a hand-entered mapping is precious).

Usage:
    python -m tools.gen_accounts [--app config/app.yaml]
"""
from __future__ import annotations

import argparse
import csv
import sys
from collections import Counter
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from config_io import DATA_ROOT, PERSONAL_CONFIG_DIR, load_app_config  # noqa: E402
from ingest import ingest  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
# accounts.yaml is personal data: it lives under the external data root.
ACCOUNTS = PERSONAL_CONFIG_DIR / "accounts.yaml"


def _archive_paths(app_path: Path) -> list[str]:
    # Reuse config_io's resolution (relative paths resolve from the data root).
    return load_app_config(app_path).resolved_archive_paths


COLLECTOR_CSV = DATA_ROOT / "transactions" / "transactions.csv"
_PLACEHOLDER = {"name": "Unnamed account", "type": "depository", "subtype": "checking",
                "institution": "Unknown"}


def collector_identity(path: Path = COLLECTOR_CSV) -> dict[str, dict]:
    """account_id -> {name, type, subtype, institution} from the collector CSV;
    {} when the CSV is absent. The name carries the mask so two cards from one
    issuer stay distinguishable."""
    if not path.exists():
        return {}
    out: dict[str, dict] = {}
    with path.open(newline="", encoding="utf-8") as fh:
        for r in csv.DictReader(fh):
            if r.get("account_id") in out:
                continue
            name = _unescape(r.get("account_name", "")) or _PLACEHOLDER["name"]
            mask = _unescape(r.get("account_mask", ""))
            out[r["account_id"]] = {
                "name": f"{name} ··{mask}" if mask else name,
                "type": r.get("account_type") or _PLACEHOLDER["type"],
                "subtype": r.get("account_subtype") or _PLACEHOLDER["subtype"],
                "institution": _unescape(r.get("institution", "")) or _PLACEHOLDER["institution"],
            }
    return out


def _unescape(cell: str) -> str:
    # The collector prefixes formula-looking cells with a quote (CSV injection guard).
    return cell[1:] if cell.startswith("'") else cell


def _yaml_str(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--app", default=str(ROOT / "config" / "app.yaml"))
    ap.add_argument("--force", action="store_true")
    args = ap.parse_args()

    if ACCOUNTS.exists() and not args.force:
        print(f"refusing to overwrite {ACCOUNTS} (use --force)", file=sys.stderr)
        return 1

    res = ingest(_archive_paths(Path(args.app)))
    counts = Counter(t.account_id for t in res.transactions)
    # The collector stamps txn_owner per record; an account's stamp seeds `person`.
    owners = {t.account_id: t.owner for t in res.transactions if t.owner}

    lines = [
        "# accounts.yaml — account_id -> person + friendly name + include?",
        "# `person` is seeded from the records' txn_owner stamp, the rest from the",
        "# collector's CSV; anything still a placeholder is yours to fill in.",
        "# Set include: false to drop an account entirely from analysis.",
        "#",
        "# Generated by `python -m tools.gen_accounts`. Safe to edit; not overwritten.",
        "accounts:",
    ]
    identity = collector_identity()
    for acct_id, n in counts.most_common():
        ident = {**_PLACEHOLDER, **identity.get(acct_id, {})}
        lines.append(f"  {acct_id}:")
        lines.append(f"    person: {owners.get(acct_id, 'Unknown')}")
        lines.append(f"    name: {_yaml_str(ident['name'])}")
        lines.append(f"    type: {ident['type']}      # depository | credit | loan | investment")
        lines.append(f"    subtype: {_yaml_str(ident['subtype'])}")
        lines.append(f"    institution: {_yaml_str(ident['institution'])}")
        lines.append("    include: true")
        lines.append(f"    # {n} transactions in current archive")
    ACCOUNTS.parent.mkdir(parents=True, exist_ok=True)
    ACCOUNTS.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {ACCOUNTS} ({len(counts)} accounts)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
